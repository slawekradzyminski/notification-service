-- notification-service baseline (schema "notification"). Users and orders live in the
-- backend; everything here is keyed by the owner's username.
--
-- Webhook tables: the backend's V14__webhooks.sql plus the V17 correlation columns, moved
-- unchanged in meaning. webhook_subscriptions.events is a comma-separated list of event wire
-- names; the signing secret is stored encrypted (WEBHOOKS_SECRET_ENCRYPTION_PASSWORD/_SALT) and
-- returned only when it is created or rotated. Ids of subscriptions imported from the backend
-- (GET /internal/v1/webhooks/export) are kept, so the identity restarts after the import.
CREATE TABLE webhook_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL,
    url varchar(2048) NOT NULL,
    description varchar(255),
    events varchar(1000) NOT NULL,
    secret varchar(512) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    consecutive_failures integer NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
    disabled_reason varchar(500),
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_webhook_subscriptions_username ON webhook_subscriptions(username);

-- The exact signed body of every attempt, so failed deliveries are retried by WebhookRetryJob and
-- redelivered on request. A PENDING row is due when next_attempt_at has passed; senders claim it by
-- moving next_attempt_at forward, so one delivery is never sent twice at once. request_id and
-- traceparent are the correlation ids of the feed event (the backend request) that queued it.
CREATE TABLE webhook_deliveries (
    id uuid PRIMARY KEY,
    subscription_id bigint NOT NULL REFERENCES webhook_subscriptions(id) ON DELETE CASCADE,
    event_id uuid NOT NULL,
    event_type varchar(64) NOT NULL,
    payload varchar(65536) NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('PENDING', 'DELIVERED', 'FAILED')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamp(6) with time zone,
    last_status_code integer,
    last_error varchar(1000),
    response_snippet varchar(500),
    duration_ms bigint,
    created_at timestamp(6) with time zone NOT NULL,
    delivered_at timestamp(6) with time zone,
    request_id varchar(128),
    traceparent varchar(55)
);
CREATE INDEX idx_webhook_deliveries_subscription ON webhook_deliveries(subscription_id, created_at);
CREATE INDEX idx_webhook_deliveries_due ON webhook_deliveries(status, next_attempt_at);

-- Built-in receivers (target URL inbox://<token>); only the last 50 requests of an inbox are kept.
CREATE TABLE webhook_inboxes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token varchar(64) NOT NULL,
    username varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_webhook_inboxes_token UNIQUE (token)
);
CREATE INDEX idx_webhook_inboxes_username ON webhook_inboxes(username);

CREATE TABLE webhook_inbox_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbox_id bigint NOT NULL REFERENCES webhook_inboxes(id) ON DELETE CASCADE,
    received_at timestamp(6) with time zone NOT NULL,
    headers varchar(16384) NOT NULL,
    body varchar(16384) NOT NULL
);
CREATE INDEX idx_webhook_inbox_requests_inbox ON webhook_inbox_requests(inbox_id, received_at);

-- Commerce emails from notification.requested feed events (outbox convention, ADR 3): request_id is
-- the backend's idempotency key; a row is pending while sent_at is null and attempts is below the
-- maximum, and the subject and body are rendered once and resent unchanged.
CREATE TABLE notification_emails (
    id uuid PRIMARY KEY,
    request_id uuid NOT NULL,
    event_id uuid NOT NULL,
    username varchar(255) NOT NULL,
    recipient_email varchar(320) NOT NULL,
    template varchar(64) NOT NULL,
    subject varchar(1000) NOT NULL,
    message varchar(16384) NOT NULL,
    properties varchar(16384) NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('QUEUED', 'SENT', 'FAILED')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamp(6) with time zone,
    sent_at timestamp(6) with time zone,
    last_error varchar(1000),
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    correlation_request_id varchar(128),
    traceparent varchar(55),
    CONSTRAINT uk_notification_emails_request UNIQUE (request_id)
);
CREATE INDEX idx_notification_emails_username ON notification_emails(username, created_at);
CREATE INDEX idx_notification_emails_due ON notification_emails(status, next_attempt_at);

-- Event feed consumer state (ADR 3): one cursor row per consumer, every handled (or skipped) event id.
CREATE TABLE event_cursors (
    consumer varchar(64) PRIMARY KEY,
    last_sequence bigint NOT NULL,
    updated_at timestamp(6) NOT NULL
);

CREATE TABLE processed_events (
    event_id uuid PRIMARY KEY,
    processed_at timestamp(6) NOT NULL
);

